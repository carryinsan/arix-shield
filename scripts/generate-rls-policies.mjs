import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const [schemaArg, outputArg] = process.argv.slice(2);
if (!schemaArg || !outputArg) {
  process.stderr.write('Usage: node scripts/generate-rls-policies.mjs <schema.sql> <output.sql>\n');
  process.exit(2);
}
const source = await readFile(resolve(schemaArg), 'utf8');
const clean = source.replace(/--[^\n]*/g, '').replace(/\/\*[\s\S]*?\*\//g, ' ');
const statements = clean.match(/CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(?:"?[a-zA-Z_][\w$]*"?\.)?"?[a-zA-Z_][\w$]*"?\s*\([\s\S]*?\)\s*;/gi) || [];
const tables = [];
for (const statement of statements) {
  const name = /CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(?:("?[a-zA-Z_][\w$]*"?)\.)?("?[a-zA-Z_][\w$]*"?)/i.exec(statement);
  if (!name) continue;
  if (!/\btenant_id\b/i.test(statement)) continue;
  const schema = (name[1] || 'public').replaceAll('"', '');
  const table = name[2].replaceAll('"', '');
  if (![schema, table].every((part) => /^[a-zA-Z_][\w$]*$/.test(part))) throw new Error('Unsafe SQL identifier in schema');
  tables.push({ schema, table });
}
if (!tables.length) throw new Error('No CREATE TABLE statements with a tenant_id column were found.');
const quote = (part) => `"${part.replaceAll('"', '""')}"`;
const lines = [
  '-- Generated by ArixShield. Review against the real schema before applying.',
  '-- Run as a dedicated non-superuser migration role that has table ownership/DDL rights.',
  '-- The runtime role must be non-superuser and NOBYPASSRLS; FORCE RLS does not constrain superusers/BYPASSRLS roles.',
  '-- Tenant context must be established by a trusted transaction adapter using set_config(..., true).',
  '-- Missing/empty arix.tenant_id evaluates to NULL and therefore denies rows.',
  'BEGIN;',
  "SELECT pg_advisory_xact_lock(hashtextextended('arixshield:tenant-rls:v1', 0));",
  "DO $$ BEGIN IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = current_user AND (rolsuper OR rolbypassrls)) THEN RAISE EXCEPTION 'ArixShield RLS migrations must not run as a superuser or BYPASSRLS role'; END IF; END $$;",
  "SELECT rolname, rolsuper, rolbypassrls FROM pg_roles WHERE rolname = current_user;",
  ''
];
for (const { schema, table } of tables) {
  const target = `${quote(schema)}.${quote(table)}`;
  const policy = quote(`arix_tenant_isolation_${table}`);
  const predicate = `(${quote('tenant_id')}::text = NULLIF(current_setting('arix.tenant_id', true), ''))`;
  lines.push(`ALTER TABLE ${target} ENABLE ROW LEVEL SECURITY;`);
  lines.push(`ALTER TABLE ${target} FORCE ROW LEVEL SECURITY;`);
  lines.push(`DROP POLICY IF EXISTS ${policy} ON ${target};`);
  lines.push(`CREATE POLICY ${policy} ON ${target} USING ${predicate} WITH CHECK ${predicate};`);
  lines.push('');
}
lines.push('COMMIT;');
await writeFile(resolve(outputArg), `${lines.join('\n')}\n`, { mode: 0o600 });
process.stdout.write(`Generated tenant RLS policies for ${tables.length} tables. Review and apply as a controlled migration.\n`);
